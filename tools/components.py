"""WolOS Design System: the component specs (design/components/*.toml) as one catalog.

  python3 -I design/tools/components.py           write design/components/catalog.json
  python3 -I design/tools/components.py --check   fail when catalog.json is not what the specs say,
                                                   or a spec breaks the schema, or (inside the wolos
                                                   checkout) docs/RULES-ui.md is not what --rules-md says
  python3 -I design/tools/components.py --rules-md          print the "Component rules" block
  python3 -I design/tools/components.py --rules-md --write  put it into docs/RULES-ui.md

The catalog is the one source the docs site (wolos.org/design), the Kit widget tests
(crates/shell/tests/kit_components.rs), the libWolkit component snapshots and the web kit node tests
read; none of them parses TOML. Standard library only (tomllib, Python 3.11+), like tools/tokens.py.
"""
import json
import os
import re
import sys
import tomllib

D = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SPECS = os.path.join(D, "components")
OUT = os.path.join(SPECS, "catalog.json")

CATEGORIES = {"actions", "selection", "input", "navigation", "containment", "communication",
              "data", "layout", "system"}
STATUS = {"proposal", "beta", "stable", "deprecated"}
DENSITIES = ("compact", "standard", "comfortable")
VARIANTS = ("light", "dark")
KITS = {"gtk", "wolkit", "web", "view"}
REQUIRED = ("schema", "id", "name", "category", "status", "summary", "implementations",
            "states", "keyboard", "a11y", "rules", "tests")
KEBAB = re.compile(r"^[a-z][a-z0-9]*(-[a-z0-9]+)*$")
RULE = re.compile(r"^RU-\d{3}$")
RULE_FIRST, RULE_LAST = 100, 999  # RU-001..099 are the shell's own rules (rules_ui.rs)
ENFORCED = re.compile(r"^(manual|RH-\d{3}|[a-z][a-z0-9_]*)$")  # manual, a ratchet id, or a test file
FEN = 4
DOC = os.path.normpath(os.path.join(D, "..", "docs", "RULES-ui.md"))
BEGIN = "<!-- component-rules:begin (generated by design/tools/components.py --rules-md; do not edit) -->"
END = "<!-- component-rules:end -->"


def problems(spec, name):
    """Sentences for everything wrong with one spec (empty when it is fine)."""
    out = []
    say = lambda s: out.append(f"{name}: {s}")
    for k in REQUIRED:
        if k not in spec:
            say(f"needs `{k}`")
    if out:
        return out
    if spec["schema"] != 1:
        say("schema is 1")
    if not KEBAB.match(spec["id"]) or f"{spec['id']}.toml" != name:
        say("id is the file name, lower-case kebab-case")
    if spec["category"] not in CATEGORIES:
        say(f"category is one of {sorted(CATEGORIES)}")
    if spec["status"] not in STATUS:
        say(f"status is one of {sorted(STATUS)}")
    if not set(spec["implementations"]) <= KITS or not spec["implementations"]:
        say(f"implementations are some of {sorted(KITS)}")
    for kit, impl in spec["implementations"].items():
        f = impl.get("file")
        if f is not None and (f.startswith("/") or ".." in f.split("/")):
            say(f"{kit} file is a path inside the repository")
    for size, dims in spec.get("sizes", {}).items():
        # A length that is not a whole fen (a 6 px meter) is allowed only when the size says which
        # and why: `off_grid = ["height"]` and `why = "..."`.
        off = dims.get("off_grid", [])
        if off and not (isinstance(dims.get("why"), str) and dims["why"].endswith(".")):
            say(f"sizes.{size} lists off_grid lengths and needs `why`, one sentence with a full stop")
        for k in off:
            if k not in ("width", "height"):
                say(f"sizes.{size}.off_grid names width or height, not {k}")
        for k in ("width", "height", "thumb", "padding"):
            v = dims.get(k)
            if v is not None and (not isinstance(v, int) or v % FEN and k in ("width", "height") and k not in off):
                say(f"sizes.{size}.{k} is a whole fen (a multiple of {FEN} px)")
    for d, m in spec.get("density", {}).items():
        if d not in DENSITIES:
            say(f"density {d} is one of {DENSITIES}")
        # `row` is the list row that holds the component, `control` the height of the control itself,
        # `row_stack` a row with its title above the control (a slider row).
        if not any(k in m for k in ("row", "control", "row_stack")):
            say(f"density.{d} gives a row or a control height")
        for k in ("row", "control", "row_stack"):
            if k in m and (not isinstance(m[k], int) or m[k] % FEN):
                say(f"density.{d}.{k} is a whole fen")
    t = spec["tests"]
    for s in t.get("states", []):
        if s not in spec["states"]:
            say(f"tests.states names {s}, which [states] does not describe")
    for d in t.get("densities", []):
        # Standard is the stylesheet as it is: a component with no density metrics tests it without a table.
        if d not in spec.get("density", {}) and d != "standard":
            say(f"tests.densities names {d}, which [density] does not give")
    for v in t.get("variants", []):
        if v not in VARIANTS:
            say(f"tests.variants are {VARIANTS}")
    for r in spec["rules"]:
        if not RULE.match(r.get("id", "")):
            say(f"rule id {r.get('id')!r} is RU-nnn")
        elif not RULE_FIRST <= int(r["id"][3:]) <= RULE_LAST:
            say(f"rule id {r['id']} is in RU-{RULE_FIRST}..{RULE_LAST} (RU-001..099 belong to rules_ui.rs)")
        if r.get("kind") not in ("do", "dont"):
            say(f"rule {r.get('id')} kind is do or dont")
        if not r.get("text", "").endswith("."):
            say(f"rule {r.get('id')} text is one sentence with a full stop")
        if "|" in r.get("text", "") or "\n" in r.get("text", ""):
            say(f"rule {r.get('id')} text has no | and no line break (it is a table cell)")
        if not r.get("enforced"):
            say(f"rule {r.get('id')} says what enforces it (a test, a ratchet id, or manual)")
        elif not ENFORCED.match(r["enforced"]):
            say(f"rule {r.get('id')} enforced is manual, an RH-nnn ratchet id or the name of a test file")
    return out


def catalog():
    """(catalog dict, problems) from every spec file."""
    specs, bad, seen = [], [], {}
    for name in sorted(os.listdir(SPECS)):
        if not name.endswith(".toml"):
            continue
        with open(os.path.join(SPECS, name), "rb") as f:
            try:
                spec = tomllib.load(f)
            except tomllib.TOMLDecodeError as e:
                bad.append(f"{name}: not TOML ({e})")
                continue
        bad += problems(spec, name)
        for r in spec.get("rules", []):
            rid = r.get("id")
            if rid in seen:
                bad.append(f"{name}: rule {rid} is also in {seen[rid]}")
            seen[rid] = name
        specs.append(spec)
    return {"schema": 1, "components": specs}, bad


def rules_md(cat):
    """The generated block of docs/RULES-ui.md: every component rule, then the ones a person checks."""
    rows = sorted(((r["id"], c["name"], r["kind"], r["text"], r["enforced"]) for c in cat["components"] for r in c["rules"]))
    out = [BEGIN, "", f"### Component rules (RU-{RULE_FIRST} to RU-{RULE_LAST}, generated)", "",
           "Each component spec in `design/components/` lists its rules; the Kit tests and `rules_ui` hold this table to the catalog. "
           "Enforced by: a test file, a ratchet id (`RH-nnn`, docs/RULES.md) or `manual`.", "",
           "| Id | Component | Kind | Rule | Enforced by |", "|---|---|---|---|---|"]
    kind = {"do": "Do", "dont": "Do not"}
    for rid, comp, k, text, enf in rows:
        out.append(f"| {rid} | {comp} | {kind[k]} | {text} | {'manual' if enf == 'manual' else '`' + enf + '`'} |")
    out += ["", "#### Component rules a person checks", ""]
    manual = [r for r in rows if r[4] == "manual"]
    out += [f"- {rid} ({comp}): {text}" for rid, comp, _, text, _ in manual] or ["None."]
    out += ["", END]
    return "\n".join(out) + "\n"


def doc_block(text):
    """(start, end) of the generated block in the document text, or None."""
    a, b = text.find(BEGIN), text.find(END)
    return None if a < 0 or b < a else (a, b + len(END) + 1)


def main(argv):
    cat, bad = catalog()
    text = json.dumps(cat, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
    if bad:
        print("\n".join(bad), file=sys.stderr)
        return 1
    if "--rules-md" in argv:
        block = rules_md(cat)
        if "--write" not in argv:
            sys.stdout.write(block)
            return 0
        doc = open(DOC, encoding="utf-8").read()
        at = doc_block(doc)
        if at is None:
            print(f"{DOC} has no component-rules block: put the begin and end markers where it goes", file=sys.stderr)
            return 1
        with open(DOC, "w", encoding="utf-8") as f:
            f.write(doc[:at[0]] + block + doc[at[1]:])
        print(f"wrote the component rules into docs/RULES-ui.md ({len(block.splitlines())} lines)")
        return 0
    if "--check" in argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("design/components/catalog.json is not what the specs say: run design/tools/components.py",
                  file=sys.stderr)
            return 1
        if os.path.exists(DOC):  # the design repository alone has no docs/
            doc = open(DOC, encoding="utf-8").read()
            at = doc_block(doc)
            if at is None or doc[at[0]:at[1]] != rules_md(cat):
                print("docs/RULES-ui.md component rules are not what the specs say: run design/tools/components.py --rules-md --write",
                      file=sys.stderr)
                return 1
        print(f"{len(cat['components'])} component specs, catalog up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, D)} ({len(cat['components'])} components)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
