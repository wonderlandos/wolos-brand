"""Write design/tokens/tokens-brand.json: the brand proposal next to colors.json (not installed,
nothing reads it yet). Every number comes from calculus.py; every colour from brand_palette().

  python3 -I design/tools/brand/tokens_brand.py [--check]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import calculus as K  # noqa: E402
from colour import oklch, from_oklch  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, "..", "..", "tokens", "tokens-brand.json"))
CUR = os.path.normpath(os.path.join(HERE, "..", "..", "tokens", "colors.json"))


def rgba(hexc, a):
    r, g, b = (int(hexc[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r},{g},{b},{a:g})"


def build():
    cur = json.load(open(CUR))
    P = K.brand_palette()
    c = {k: v[0] for k, v in P.items()}
    L0, C0, h0 = oklch(K.BASE)
    hue = {e: K.hue_of(e) for e in ("fire", "earth", "wood", "water")}

    def st(el, k, cf):
        return from_oklch(K.ladder(L0, k), C0 * cf / 21, hue[el])

    status_l = {"red": st("fire", -2, 15), "orange": st("fire", 1, 16) if False else from_oklch(K.ladder(L0, 0), C0 * 15 / 21, (hue["fire"] + hue["earth"]) / 2),
                "yellow": c["earth-deep"], "green": st("wood", -2, 14), "blue": st("water", -3, 14)}
    status_d = {"red": st("fire", 6, 13), "orange": from_oklch(K.ladder(L0, 8), C0 * 13 / 21, (hue["fire"] + hue["earth"]) / 2),
                "yellow": c["earth"], "green": st("wood", 8, 12), "blue": st("water", 8, 12)}
    ink = c["light.text"]
    t = {
        "_about": ("WolOS brand proposal (docs/adr/brand-calculus.md). Generated by design/tools/brand/tokens_brand.py from "
                   "calculus.py; scored against colors.json by design/tools/brand/score_tokens.py. Not installed."),
        "base": K.BASE,
        "accent": {"light": c["accent"], "dark": c["accent"]},
        "light": {
            "bg": c["light.bg"], "surface": c["light.surface"], "surface-2": c["light.surface-2"],
            "menubar": rgba(c["light.bg"], 0.72), "dock": rgba(c["light.surface"], 0.55),
            "border": rgba(ink, 0.12), "text": ink, "text-2": c["light.text-2"],
            "shadow": rgba(c["light.text"], 0.18), **status_l,
            "accent": c["accent"], "accent-fg": "#FFFFFF", "accent-text": c["light.accent-text"],
            "selection": rgba(c["accent"], 0.22)},
        "dark": {
            "bg": c["dark.bg"], "surface": c["dark.surface"], "surface-2": c["dark.surface-2"],
            "menubar": rgba(c["dark.bg"], 0.62), "dock": rgba(c["dark.surface"], 0.50),
            "border": rgba(c["dark.text"], 0.12), "text": c["dark.text"], "text-2": c["dark.text-2"],
            "shadow": rgba(from_oklch(K.ladder(L0, -18), C0 * 2 / 21, h0), 0.45), **status_d,
            "accent": c["accent"], "accent-fg": "#FFFFFF", "accent-text": c["dark.accent-text"],
            "selection": rgba(c["dark.accent-text"], 0.30)},
        "elements": {k: {"hex": v[0], "formula": v[1], "element": v[2], "use": v[3]} for k, v in P.items()},
        "icon": cur["icon"],
        "space": {f"space-{i + 1}": f"{K.px(n)}px" for i, n in enumerate((1, 2, 3, 4, 6, 10, 15, 21))},
        "size": {"toolbar": "40px", "sidebar": "240px", "sidebar-item": "24px", "row": "40px",
                 "control": "32px", "content-max": "576px", "status-bar": "24px", "icon-row": "16px"},
        "radius": {"sm": "8px", "md": "12px", "lg": "16px", "window": "12px", "dock": "24px",
                   "icon": cur["radius"]["icon"]},
        "type": {k: {"size": f"{v['size']}px", "line": f"{v['line']}px"} for k, v in K.type_scale().items()},
        "light-source": {"vector": [round(K.LIGHT[0], 4), round(K.LIGHT[1], 4)], "from": "upper left, steep (dx:dy = 1:2)",
                         "gloss": {"edge": "upper-left", "opacity": 0.5, "fade": 0.45}},
        "elevation": {"1": {"offset": [1, 2], "blur": "4px"}, "2": {"offset": [2, 4], "blur": "12px"},
                      "3": {"offset": [3, 6], "blur": "24px"}},
        "blur": cur["blur"],
        "font": cur["font"] | {"size": "13px", "size-menubar": "13px"},
        "planes": {"ground": round(K.PLANES[0], 3), "second": round(K.PLANES[1], 3), "first": round(K.PLANES[2], 3)},
        "module": {"fen_px": K.U, "fen_rem": K.U / K.REM, "named_fen": list(K.NAMED),
                   "ruler_fen": K.RULER, "bands": list(K.BANDS), "good_bands": sorted(K.GOOD_BANDS)},
        "wallpaper": {"light": "brand-courtyard-day.svg", "dark": "brand-moon-gate-night.svg"},
    }
    return t


def main(argv):
    s = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in argv:
        if open(OUT).read() != s:
            sys.exit("tokens-brand.json is stale: run tools/brand/tokens_brand.py")
        return
    open(OUT, "w").write(s)
    print("wrote", OUT)


if __name__ == "__main__":
    main(sys.argv[1:])
